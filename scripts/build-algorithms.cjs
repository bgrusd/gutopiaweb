// Bundle the app's unchanged, dependency-free CommonJS demo kernels for the browser.
// Refresh models/*.js from CrohnsTrackerApp/demoAlgorithms before rebuilding.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const names = ["math", "dataset", "workflows"];
const modules = names
  .map(
    (name) =>
      `${JSON.stringify("./" + name)}: function(module, exports, require) {\n${fs.readFileSync(path.join(root, "assets/algorithms/models", name + ".js"), "utf8")}\n}`,
  )
  .join(",\n");
fs.writeFileSync(
  path.join(root, "assets/algorithms/kernels.js"),
  `/* Generated by scripts/build-algorithms.cjs; source: models/*.js. No network or personal data access. */\n(function() {\n'use strict';\nconst modules = {${modules}};\nconst cache = {};\nfunction require(id) { if (!modules[id]) throw new Error('Unknown module: ' + id); if (!cache[id]) { const module = { exports: {} }; cache[id] = module; modules[id](module, module.exports, require); } return cache[id].exports; }\nwindow.GutopiaDemo = { ...require('./dataset'), ...require('./workflows') };\n})();\n`,
);
